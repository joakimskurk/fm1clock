"""The clock's sound tables, from the fitted model (tools/clk_model.json, tools/fit_model.py): firmware/gen/clk_tables.h.
Integers only (the chip has no FPU): phase steps of 2^32 per cycle at 44.1 kHz, levels in Q31 of the output's full
scale, decays as Q32 multipliers per step of frames. Plain Python, no numpy.

  python3 tools/gen_tables.py [--check]
"""
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "firmware" / "gen" / "clk_tables.h"
FS = 44100
GAIN = 2.6                  # the output against the recording: the lone strike's peak at ~0.6 of full scale
SUB = 16                    # frames per envelope step of the gong (clk_engine.h)
TSTEP = 4                   # frames per envelope step of the ticks
BLOCK = 256                 # frames per audio block (platform.c HALF_FRAMES)
SINQ_N = 4096               # a quarter of the sine table (16384 entries)


def inc(f):
    return int(round(f * 2 ** 32 / FS)) & 0xFFFFFFFF


def dec(tau, frames):
    return min(int(round(math.exp(-frames / (FS * tau)) * 2 ** 32)), 0xFFFFFFFF)


def q31(a):
    v = int(round(a * GAIN * 2 ** 31))
    assert 0 <= v < 2 ** 31, a
    return v


def carray(name, ctype, vals, per=8):
    vals = list(vals)
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(f"{v}u" if ctype.startswith("uint") else str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return "\n".join(out)


def build():
    m = json.loads((ROOT / "tools" / "clk_model.json").read_text())
    modes, fm = m["modes"], m["fm"]
    K = m["k_fm"]
    NT = m["nt"]
    h = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* generated by tools/gen_tables.py from tools/clk_model.json (fitted to the reference recording by",
         " * tools/analyze_ref.py and tools/fit_model.py): do not edit */",
         "#pragma once", "#include <stdint.h>",
         f"#define NG {len(modes)}u            /* the gong's modes, strongest first (their energy a^2 tau) */",
         f"#define K_FM {K}u            /* the first K_FM carry a modulator */",
         f"#define NT {NT}u            /* operators per tick bank */",
         f"#define CLK_SUB {SUB}u", f"#define CLK_TSTEP {TSTEP}u", f"#define CLK_BLOCK {BLOCK}u",
         f"#define TRAIN_FRAMES {int(round(m['train']['interval'] * FS))}u   /* hit to hit in a strike train */",
         f"#define CLICK_FRAMES {int(round(m['click_before'] * FS))}u    /* the release click before a hit */",
         f"#define AFTER_FRAMES {int(round(0.115 * FS))}u   /* the tock's second click after it */"]
    # the sine, a quarter: SINQ[i] = sin(i / 4096 * pi / 2), Q15, i = 0..4096
    h.append(carray("SINQ", "int16_t", [int(round(32767 * math.sin(i / SINQ_N * math.pi / 2))) for i in range(SINQ_N + 1)], 16))
    h.append("/* the gong's carriers: phase step, level at the hit (Q31), decay per CLK_SUB and per CLK_BLOCK frames (Q32),")
    h.append(" * phase at the hit (the recording's cos as the table's sin) */")
    h.append(carray("G_INC", "uint32_t", [inc(d["f"]) for d in modes]))
    h.append(carray("G_AMP", "uint32_t", [q31(d["a"]) for d in modes]))
    h.append(carray("G_DEC", "uint32_t", [dec(d["tau"], SUB) for d in modes]))
    h.append(carray("G_DEC_BLOCK", "uint32_t", [dec(d["tau"], BLOCK) for d in modes]))
    h.append(carray("G_PH", "uint32_t", [int(round(((d["ph"] + math.pi / 2) / (2 * math.pi)) % 1.0 * 2 ** 32)) & 0xFFFFFFFF for d in modes]))
    h.append("/* the modulators of the first K_FM: phase step, index at the hit (2^32 / 2pi per radian, / 2^15: times the")
    h.append(" * Q15 sine it is a phase), its decay per CLK_SUB frames (Q32), the carrier's boost at the hit (Q12) */")
    h.append(carray("F_INC", "uint32_t", [inc(f["r"] * d["f"]) for f, d in zip(fm, modes)]))
    h.append(carray("F_I0", "uint32_t", [int(round(f["I"] / (2 * math.pi) * 2 ** 17)) for f in fm]))
    h.append(carray("F_DEC", "uint32_t", [dec(f["tauI"], SUB) for f in fm]))
    h.append(carray("F_B", "uint32_t", [int(round(f["B"] * 4096)) for f in fm]))
    h.append("/* the hammer: its strength through a strike train (Q15), the first blow the strongest */")
    g = m["train"]["gains"]
    gains = [g[0], g[1]] + [sum(g[2:]) / len(g[2:])]
    h.append(carray("HAMMER", "uint32_t", [int(round(32767 * v)) for v in gains]))
    h.append("/* the ticks' rise: 1 - e^(-t / ta), per frame towards 1 by this much (Q15) */")
    h.append(carray("T_ATK", "uint32_t", [int(round(32768 * (1 - math.exp(-1 / (FS * m[n + "_attack"]))))) for n in ("tick", "tock")]))
    for k, name in enumerate(("tick", "tock")):
        b = m[name]
        h.append(f"/* {name}: phase step, level (Q31), decay per CLK_TSTEP frames (Q32) */")
        h.append(carray(f"T{k}_INC", "uint32_t", [inc(o["f"]) for o in b]))
        h.append(carray(f"T{k}_AMP", "uint32_t", [q31(o["a"]) for o in b]))
        h.append(carray(f"T{k}_DEC", "uint32_t", [dec(o["tau"], TSTEP) for o in b]))
    return "\n".join(h) + "\n"


def main():
    h = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != h:
            print("firmware/gen/clk_tables.h is not what tools/gen_tables.py makes: run it")
            return 1
        print("clk_tables.h: up to date")
        return 0
    OUT.write_text(h)
    print(f"{OUT.relative_to(ROOT)}: {h.count(chr(10))} lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
