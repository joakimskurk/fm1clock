def rgb565(r, g_, b):
    return (r >> 3) << 11 | (g_ >> 2) << 5 | b >> 3


def hexrgb(s):
    return tuple(int(s[i:i + 2], 16) for i in (1, 3, 5))


def indexed(grids):
    """grids of (r, g, b) or None -> one palette and, a grid each, its pixels as indices (255: clear)"""
    pal = []
    out = []
    for g in grids:
        px = []
        for row in g:
            for c in row:
                if c is None:
                    px.append(255)
                    continue
                if c not in pal:
                    pal.append(c)
                px.append(pal.index(c))
        out.append(px)
    assert len(pal) < 255, len(pal)
    return pal, out


def carr(name, typ, vals, per=24, fmt="{}"):
    s = [f"static const {typ} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        s.append("    " + ", ".join(fmt.format(v) for v in vals[i:i + per]) + ",")
    s.append("};")
    return "\n".join(s)


def build():
    hpal, hams = indexed(ham_sprites.hamsters())
    dpal, frames = indexed(ham_sprites.drummer())
    o = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* HamsterSynth's pictures. Made by tools/gen_ham_art.py of tools/ham_sprites.py: do not edit. */",
         "#pragma once", "#include <stdint.h>", ""]
    o.append(f"#define HAM_W {ham_sprites.W}u                               /* a hamster, its pixels (2 x 2 on the screen) */")
    o.append(f"#define HAM_H {ham_sprites.H}u")
    o.append(carr("HAM_PAL", "uint16_t", [rgb565(*c) for c in hpal], 9, "0x{:04X}"))
    o.append("static const uint8_t HAM_SPR[8][HAM_W * HAM_H] = {       /* 255: clear */")
    for px in hams:
        o.append("    {" + ",".join(str(v) for v in px) + "},")
    o.append("};")
    o.append(carr("HAM_TINT", "uint16_t", [rgb565(*ham_sprites.FUR[k["fur"]][1]) for k in ham_sprites.KINDS], 8, "0x{:04X}")
             .replace("] = {", "] = {                /* each hamster's fur: its steps' stripe */", 1))
    o.append(f"#define DRUM_W {ham_sprites.DW}u                               /* the drummer, its pixels (2 x 2) */")
    o.append(f"#define DRUM_H {ham_sprites.DH}u")
    o.append(carr("DRUM_PAL", "uint16_t", [rgb565(*c) for c in dpal], 8, "0x{:04X}"))
    o.append("static const uint8_t DRUM_SPR[4][DRUM_W * DRUM_H] = {")
    for px in frames:
        o.append("    {" + ",".join(str(v) for v in px) + "},")
    o.append("};")
    o.append("/* the logo's letters, 7 x 9: a row a byte, bit 6 the left pixel */")
    o.append('#define LOGO_CHARS "HAMSTERYNOC"')
    o.append("static const uint8_t LOGO_FONT[11][9] = {")
    for c in "HAMSTERYNOC":
        o.append("    {" + ", ".join(str(int(r, 2)) for r in LOGO[c]) + "},")
    o.append("};")
    o.append("/* the text's font, 5 x 7: a row a byte, bit 4 the left pixel; PF_CODE: each glyph's Unicode code point */")
    o.append(f"#define PF_N {len(ORDER)}u")
    o.append(carr("PF_CODE", "uint16_t", [ord(c) for c in ORDER], 12, "0x{:04X}"))
    o.append("static const uint8_t PF_GLYPH[PF_N][7] = {")
    for c in ORDER:
        o.append("    {" + ", ".join(str(int(r.replace("#", "1").replace(".", "0"), 2)) for r in F[c]) + "},")
    o.append("};")
    o.append("/* the small font, 5 rows: a row a byte, bit (width - 1) the left pixel; SF_W: each glyph's width */")
    o.append(f"#define SF_N {len(SORDER)}u")
    o.append(carr("SF_CODE", "uint16_t", [ord(c) for c in SORDER], 12, "0x{:04X}"))
    o.append(carr("SF_W", "uint8_t", [len(S[c][0]) for c in SORDER], 24))
    o.append("static const uint8_t SF_GLYPH[SF_N][5] = {")
    for c in SORDER:
        o.append("    {" + ", ".join(str(int(r.replace("#", "1").replace(".", "0"), 2)) for r in S[c]) + "},")
    o.append("};")
    return "\n".join(o) + "\n"


def sheet(path):
    """the pictures as one image, to look at: the hamsters on the page's cream, the drummer's frames, the font"""
    sc = 6
    hams, drums = ham_sprites.hamsters(), ham_sprites.drummer()
    hw, hh, dw, dh = ham_sprites.W, ham_sprites.H, ham_sprites.DW, ham_sprites.DH
    im = Image.new("RGB", (4 * (hw + 4) * sc, (2 * (hh + 4) + 2 * (dh + 4) + 20) * sc), (247, 236, 215))

    def put(g, x0, y0, bg=None):
        if bg:
            im.paste(bg, (x0, y0, x0 + len(g[0]) * sc, y0 + len(g) * sc))
        for y, row in enumerate(g):
            for x, c in enumerate(row):
                if c:
                    im.paste(c, (x0 + x * sc, y0 + y * sc, x0 + x * sc + sc, y0 + y * sc + sc))
    for i, g in enumerate(hams):
        put(g, (i % 4) * (hw + 4) * sc + 2 * sc, (i // 4) * (hh + 4) * sc + 2 * sc)
    for f, g in enumerate(drums):
        put(g, (f % 2) * (dw + 2) * sc, (2 * (hh + 4) + (f // 2) * (dh + 4)) * sc, (0x17, 0x34, 0x40))
    for i, c in enumerate(ORDER):
        for y, r in enumerate(F[c]):
            for x, b in enumerate(r):
                if b == "#":
                    xx, yy = (i % 36) * 6 + x + 2, 2 * (hh + 4) + 2 * (dh + 4) + 2 + (i // 36) * 9 + y
                    im.paste((9, 26, 37), (xx * sc // 2, yy * sc, xx * sc // 2 + sc // 2, yy * sc + sc // 2))
    im.save(path)


def main():
    if "--sheet" in sys.argv:
        sheet(sys.argv[sys.argv.index("--sheet") + 1])
        return 0
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("ham_art.h: differs from what tools/gen_ham_art.py makes (run it)")
            return 1
        print("ham_art.h: up to date")
        return 0
    OUT.write_text(text)
    print(f"{OUT.relative_to(ROOT)}: {len(text)} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
